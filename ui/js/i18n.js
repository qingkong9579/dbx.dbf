  let current = "zh-CN";

  function detect() {
    try {
      const host = g.dbxPlugin;
      const l = host && host.locale;
      if (l && DICT[l]) return l;
      if (l && /^zh/i.test(l)) return "zh-CN";
      const nav = (g.navigator && g.navigator.language) || "";
      if (/^zh/i.test(nav)) return "zh-CN";
    } catch (e) {
      /* ignore */
    }
    return "zh-CN";
  }

  function t(key, vars) {
    const table = DICT[current] || DICT["zh-CN"];
    let s = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : DICT["zh-CN"][key];
    if (s === undefined) s = key;
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
    }
    return s;
  }

  function setLocale(loc) {
    current = DICT[loc] ? loc : "zh-CN";
    document.documentElement.lang = current;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = t(key);
      if (el.hasAttribute("data-i18n-html")) el.innerHTML = val;
      else el.textContent = val;
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
    scope.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
  }

  g.I18N = {
    t,
    apply,
    setLocale,
    detect,
    get locale() {
      return current;
    },
    locales: [
      { id: "zh-CN", label: "简体中文" },
      { id: "en-US", label: "English" }
    ]
  };
